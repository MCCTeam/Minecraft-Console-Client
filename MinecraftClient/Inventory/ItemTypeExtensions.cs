        public static bool IsFood(this ItemType m)
        {
            return s_food.Contains(m);
        }

        public static bool IsStackable(this ItemType m)
        {
            return !s_nonStackable.Contains(m);
        }

        public static int StackCount(this ItemType m)
        {
            // NOTE: Preserved exact original MCC precedence for backward compatibility with scripts
            if (m.IsStackable())
                return 64;
            else if (s_stack16.Contains(m))
                return 16;
            else
                return 1;
        }
